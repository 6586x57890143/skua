// Garment is the garment livery key is made into, for tools/ppcard.
func Garment(key string) []string { return garments[key] }

// mirror is a garment from its left half: the right half is the left
// turned over, its lit cells in shade.
func mirror(left ...string) []string {
	g := make([]string, len(left))
	for i, l := range left {
		var b strings.Builder
		b.WriteString(l)
		for j := len(l) - 1; j >= 0; j-- {
			c := l[j]
			if c == '1' {
				c = '3'
			}
			b.WriteByte(c)
		}
		g[i] = b.String()
	}
	return g
}
