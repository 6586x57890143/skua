// Command foreverart rebuilds Blizzard's WoW Forever class icons on skua's
// 24 cell grid and writes them as text grids to
// tools/sprites/forever_icons.go, which go run ./tools/sprites draws. Only
// the rebuilt grids are kept: the icons themselves are fetched each run
// and never written to disk.
//
//	go run ./tools/foreverart
//
// The icon ids are what /data/wow/media/playable-class/{id} answers in the
// static-forever namespace; they are public on Blizzard's render host.
package main

import (
	"bytes"
	"fmt"
	"image"
	"image/color"
	_ "image/jpeg"
	"log"
	"math"
	"net/http"
	"os"
	"slices"
	"strings"
	"time"
)

// classIcons is each class's icon on render.worldofwarcraft.com.
var classIcons = map[string]string{
	"warrior": "626008", "paladin": "626003", "hunter": "626000", "rogue": "626005", "priest": "626004",
	"shaman": "626006", "mage": "626001", "warlock": "626007", "druid": "625999",
}

const (
	cells  = 24
	inks   = 8
	border = 4 // Blizzard's bevel, cropped off the 56px icon
)

// outline is pp's dark outline, the grid's outer ring.
var outline = color.NRGBA{0x14, 0x12, 0x18, 0xFF}

func main() {
	c := &http.Client{Timeout: 20 * time.Second}
	var out strings.Builder
	out.WriteString(`// Code generated by go run ./tools/foreverart; DO NOT EDIT.

package main

import "image/color"

// foreverClassIcons are Blizzard's WoW Forever class icons rebuilt on the
// 24 cell grid: quantised to 8 inks, resampled by majority, the outer ring
// pp's dark outline. Each cell is an index into ink.
var foreverClassIcons = map[string]inkGrid{
`)
	for _, name := range slices.Sorted(keys(classIcons)) {
		img := fetch(c, "https://render.worldofwarcraft.com/forever-us/icons/56/"+classIcons[name]+".jpg")
		ink, grid := rebuild(img)
		fmt.Fprintf(&out, "\t%q: {\n\t\tink: []color.NRGBA{", name)
		for i, k := range ink {
			if i > 0 {
				out.WriteString(", ")
			}
			fmt.Fprintf(&out, "{0x%02X, 0x%02X, 0x%02X, 0xFF}", k.R, k.G, k.B)
		}
		out.WriteString("},\n\t\tgrid: []string{\n")
		for _, row := range grid {
			fmt.Fprintf(&out, "\t\t\t%q,\n", row)
		}
		out.WriteString("\t\t},\n\t},\n")
	}
	out.WriteString("}\n")
	if err := os.WriteFile("tools/sprites/forever_icons.go", []byte(out.String()), 0o644); err != nil {
		log.Fatal(err)
	}
	log.Print("wrote tools/sprites/forever_icons.go; now go run ./tools/sprites")
}

func keys(m map[string]string) func(func(string) bool) {
	return func(yield func(string) bool) {
		for k := range m {
			if !yield(k) {
				return
			}
		}
	}
}

func fetch(c *http.Client, url string) image.Image {
	res, err := c.Get(url)
	if err != nil {
		log.Fatal(err)
	}
	defer func() { _ = res.Body.Close() }()
	if res.StatusCode != http.StatusOK {
		log.Fatalf("%s: %s", url, res.Status)
	}
	var b bytes.Buffer
	if _, err := b.ReadFrom(res.Body); err != nil {
		log.Fatal(err)
	}
	img, _, err := image.Decode(&b)
	if err != nil {
		log.Fatal(err)
	}
	return img
}

// rebuild quantises the icon's inside to inks colours, then gives each
// cell the ink most of its pixels have (UX.md: majority, never one sample).
// Index 0 is the outline.
func rebuild(img image.Image) ([]color.NRGBA, []string) {
	r := img.Bounds().Inset(border)
	var px []color.NRGBA
	for y := r.Min.Y; y < r.Max.Y; y++ {
		for x := r.Min.X; x < r.Max.X; x++ {
			px = append(px, color.NRGBAModel.Convert(img.At(x, y)).(color.NRGBA))
		}
	}
	pal := kmeans(px, inks-1)
	ink := append([]color.NRGBA{outline}, pal...)
	grid := make([]string, cells)
	for cy := range cells {
		row := make([]byte, cells)
		for cx := range cells {
			if cx == 0 || cy == 0 || cx == cells-1 || cy == cells-1 {
				row[cx] = '0'
				continue
			}
			votes := make([]int, len(pal))
			x0, x1 := r.Min.X+cx*r.Dx()/cells, r.Min.X+(cx+1)*r.Dx()/cells
			y0, y1 := r.Min.Y+cy*r.Dy()/cells, r.Min.Y+(cy+1)*r.Dy()/cells
			for y := y0; y < y1; y++ {
				for x := x0; x < x1; x++ {
					votes[nearest(pal, color.NRGBAModel.Convert(img.At(x, y)).(color.NRGBA))]++
				}
			}
			best := 0
			for i, v := range votes {
				if v > votes[best] {
					best = i
				}
			}
			row[cx] = byte('1' + best)
		}
		grid[cy] = string(row)
	}
	return ink, grid
}

func d2(a, b color.NRGBA) float64 {
	dr, dg, db := float64(a.R)-float64(b.R), float64(a.G)-float64(b.G), float64(a.B)-float64(b.B)
	return dr*dr + dg*dg + db*db
}

func nearest(pal []color.NRGBA, c color.NRGBA) int {
	best, bd := 0, math.MaxFloat64
	for i, p := range pal {
		if d := d2(p, c); d < bd {
			best, bd = i, d
		}
	}
	return best
}

// kmeans is k colours for px, seeded evenly along brightness so a run is
// the same every time.
func kmeans(px []color.NRGBA, k int) []color.NRGBA {
	sorted := slices.Clone(px)
	slices.SortFunc(sorted, func(a, b color.NRGBA) int {
		return (int(a.R) + int(a.G) + int(a.B)) - (int(b.R) + int(b.G) + int(b.B))
	})
	cent := make([]color.NRGBA, k)
	for i := range k {
		cent[i] = sorted[(2*i+1)*len(sorted)/(2*k)]
	}
	for range 20 {
		sum := make([][3]float64, k)
		n := make([]float64, k)
		for _, p := range px {
			i := nearest(cent, p)
			sum[i][0] += float64(p.R)
			sum[i][1] += float64(p.G)
			sum[i][2] += float64(p.B)
			n[i]++
		}
		for i := range cent {
			if n[i] > 0 {
				cent[i] = color.NRGBA{uint8(sum[i][0] / n[i]), uint8(sum[i][1] / n[i]), uint8(sum[i][2] / n[i]), 0xFF}
			}
		}
	}
	return cent
}
